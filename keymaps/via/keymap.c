bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        /* KEYBOARD PET STATUS START */

        case KC_LCTL:
        case KC_RCTL:
            if (record->event.pressed) {
                isSneaking = true;
            } else {
                isSneaking = false;
            }
            break;
        case KC_SPC:
            if (record->event.pressed) {
                isJumping = true;
                showedJump = false;
            } else {
                isJumping = false;
            }
            break;

        /* KEYBOARD PET STATUS END */
    }
    return true;
}


// ЩОБ ПЕС БІГАВ ПРИГАВ НА ВСІХ КЛАВІШАХ А НЕ ТІЛЬКИ НА ЛІТЕРАХ
bool wpm_keycode_user(uint16_t keycode) {
    // Якщо це tap-модифікатори або layer tap'и — витягуємо базову кнопку
    if ((keycode >= QK_MOD_TAP && keycode <= QK_MOD_TAP_MAX) ||
        (keycode >= QK_LAYER_TAP && keycode <= QK_LAYER_TAP_MAX) ||
        (keycode >= QK_MODS && keycode <= QK_MODS_MAX)) {
        keycode = keycode & 0xFF;
    } else if (keycode > 0xFF) {
        keycode = 0;
    }

    // Перевірка:
    if (
        // Літери A-Z
        (keycode >= KC_A && keycode <= KC_Z) ||
        // Цифри 1-0 (верхній рядок)
        (keycode >= KC_1 && keycode <= KC_0) ||
        // Символи від TAB до /
        (keycode >= KC_TAB && keycode <= KC_SLSH) ||
        // NumPad цифри 0-9
        (keycode >= KC_P1 && keycode <= KC_P0) ||
        // Інші важливі NumPad клавіші (ENTER, ., +, -, *, /)
        keycode == KC_PENT ||
        keycode == KC_PDOT ||
        keycode == KC_PPLS ||
        keycode == KC_PMNS ||
        keycode == KC_PSLS ||
        keycode == KC_PAST ||
        keycode == KC_PEQL
    ) {
        return true;
    }

    return false;
}

